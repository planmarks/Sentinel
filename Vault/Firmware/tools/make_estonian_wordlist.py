#!/usr/bin/env python3
"""Curate a 2048-word Estonian Diceware list from a frequency corpus, then emit
the C header the firmware embeds.

Source used for the shipped candidate list:
  https://raw.githubusercontent.com/hermitdave/FrequencyWords/master/content/2018/et/et_50k.txt
  (OpenSubtitles 2018, "word <space> count" per line, most-frequent first)

Pipeline:
  lowercase -> keep only Estonian letters -> ASCII-fold (o a o u s z)
  -> keep length 4..8 -> drop words containing c q w x y z f (foreign/names)
  -> first unique 4-letter prefix wins (most frequent) -> take 2048 -> sort.

Usage:
  python tools/make_estonian_wordlist.py et_50k.txt src/estonian_words.h [words.txt]

This is a *candidate* generator; review the output and hand-prune names/awkward
forms before production. Always re-run validate_wordlist.py on the result.
"""
import sys

FOLD = str.maketrans({'õ':'o','ä':'a','ö':'o','ü':'u','š':'s','ž':'z'})
ALLOWED = set("abcdefghijklmnopqrstuvwxyzõäöüšž")
FOREIGNISH = set("cqwxyzf")   # in Estonian these are almost only loanwords/names

def curate(freq_path):
    seen_word, seen_prefix, chosen = set(), set(), []
    for line in open(freq_path, encoding="utf-8"):
        parts = line.split()
        if len(parts) < 2:
            continue
        w = parts[0].strip().lower()
        if not w or any(ch not in ALLOWED for ch in w):
            continue
        f = w.translate(FOLD)
        if not (f.isascii() and f.isalpha()):
            continue
        if not (4 <= len(f) <= 8):
            continue
        if any(ch in FOREIGNISH for ch in f):
            continue
        if f in seen_word or f[:4] in seen_prefix:
            continue
        seen_word.add(f); seen_prefix.add(f[:4]); chosen.append(f)
        if len(chosen) == 2048:
            break
    if len(chosen) != 2048:
        raise SystemExit(f"only {len(chosen)} words after filtering; relax the rules")
    chosen.sort()
    return chosen

def emit_header(words, header_path):
    with open(header_path, "w", newline="\n") as f:
        f.write("// Estonian Diceware wordlist (2048 words) - CANDIDATE / test list.\n")
        f.write("// Generated by tools/make_estonian_wordlist.py; review before production.\n")
        f.write("#ifndef ESTONIAN_WORDS_H\n#define ESTONIAN_WORDS_H\n\n")
        f.write("static const char* const ET_WORDS[2048] = {\n")
        for i in range(0, 2048, 4):
            f.write("  " + ", ".join('"%s"' % w for w in words[i:i+4]) + ",\n")
        f.write("};\n\n#endif\n")

if __name__ == "__main__":
    if len(sys.argv) < 3:
        print(__doc__); sys.exit(2)
    words = curate(sys.argv[1])
    emit_header(words, sys.argv[2])
    if len(sys.argv) > 3:
        open(sys.argv[3], "w", newline="\n").write("\n".join(words) + "\n")
    print(f"ok: 2048 words -> {sys.argv[2]}")
