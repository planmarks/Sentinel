#!/usr/bin/env python3
"""Muru Vault firmware signing tool (Ed25519 secure boot).

Subcommands:
  keygen                         -> make a signing keypair; write the private key
                                    to tools/fw_signing_key.pem and the public key
                                    into bootloader/boot_pubkey.c (baked into the BL).
  sign  <app.bin> <version> <manifest.out>
                                 -> SHA-256(core||payload), Ed25519-sign it, emit a
                                    96-byte manifest (32-byte core + 64-byte sig).
  verify <app.bin> <manifest.bin>-> re-check a manifest against the public key.
  merge <bootloader.bin> <manifest.bin> <app.bin> <out.hex>
                                 -> combined Intel HEX for one-shot flashing.

Flash map (keep in sync with src/fwimage.h):
  bootloader @ 0x08000000, manifest @ 0x08007800, app @ 0x08008000.
Ed25519 signs the 32-byte digest, exactly as the device verifies it.
"""
import sys, os, struct, hashlib
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey, Ed25519PublicKey
from cryptography.hazmat.primitives import serialization

HERE = os.path.dirname(os.path.abspath(__file__))
KEY_PEM   = os.path.join(HERE, "fw_signing_key.pem")
PUBKEY_C  = os.path.join(HERE, "..", "bootloader", "boot_pubkey.c")

FW_MAGIC  = 0x5746564D          # 'M','V','F','W'
APP_BASE  = 0x08008000
APP_MAX   = 96 * 1024
MANIFEST_ADDR = 0x08007800
BL_BASE   = 0x08000000

def build_core(version, length):
    # magic, version, length, load_addr, reserved[16]  -> 32 bytes
    return struct.pack("<IIII", FW_MAGIC, version, length, APP_BASE) + b"\x00" * 16

def digest(core, payload):
    h = hashlib.sha256(); h.update(core); h.update(payload); return h.digest()

def keygen():
    if os.path.exists(KEY_PEM):
        print("refusing to overwrite", KEY_PEM, "(delete it first to rotate keys)"); sys.exit(1)
    sk = Ed25519PrivateKey.generate()
    pem = sk.private_bytes(serialization.Encoding.PEM,
                           serialization.PrivateFormat.PKCS8,
                           serialization.NoEncryption())
    with open(KEY_PEM, "wb") as f: f.write(pem)
    try: os.chmod(KEY_PEM, 0o600)
    except Exception: pass
    pub = sk.public_key().public_bytes(serialization.Encoding.Raw,
                                        serialization.PublicFormat.Raw)
    rows = "\n".join("  " + " ".join(f"0x{b:02x}," for b in pub[i:i+8]) for i in range(0, 32, 8))
    with open(PUBKEY_C, "w", newline="\n") as f:
        f.write("/* Auto-generated by tools/fw_sign.py keygen. The matching private key is in\n"
                " * tools/fw_signing_key.pem - KEEP IT SECRET and back it up; losing it means\n"
                " * no future signed updates for devices carrying this bootloader. */\n"
                "#include <stdint.h>\n\n"
                "const uint8_t BOOT_PUBKEY[32] = {\n" + rows + "\n};\n")
    print("wrote", KEY_PEM, "and", os.path.relpath(PUBKEY_C, HERE))
    print("public key:", pub.hex())

def load_sk():
    with open(KEY_PEM, "rb") as f:
        return serialization.load_pem_private_key(f.read(), password=None)

def sign(app_path, version, out_path):
    payload = open(app_path, "rb").read()
    if len(payload) == 0 or len(payload) > APP_MAX:
        print("bad payload size", len(payload)); sys.exit(1)
    core = build_core(int(version, 0), len(payload))
    d = digest(core, payload)
    sig = load_sk().sign(d)                      # Ed25519 over the 32-byte digest
    assert len(sig) == 64
    with open(out_path, "wb") as f: f.write(core + sig)
    print(f"signed: version={int(version,0)} len={len(payload)} digest={d.hex()}")
    print("manifest ->", out_path, f"({len(core)+len(sig)} bytes)")

def verify(app_path, manifest_path):
    payload = open(app_path, "rb").read()
    man = open(manifest_path, "rb").read()
    core, sig = man[:32], man[32:96]
    magic, version, length, load = struct.unpack("<IIII", core[:16])
    if magic != FW_MAGIC: print("bad magic"); sys.exit(1)
    if length != len(payload): print("length mismatch", length, len(payload)); sys.exit(1)
    if load != APP_BASE: print("bad load addr"); sys.exit(1)
    d = digest(core, payload)
    pub = load_sk().public_key()
    try:
        pub.verify(sig, d)
    except Exception as e:
        print("SIGNATURE INVALID:", e); sys.exit(1)
    print(f"OK: signature valid (version={version}, len={length})")

# --- minimal Intel HEX writer ---
def ihex(records):
    out = []
    def rec(count, addr, rtype, data):
        b = bytes([count, (addr >> 8) & 0xff, addr & 0xff, rtype]) + data
        chk = (-sum(b)) & 0xff
        return ":" + b.hex().upper() + f"{chk:02X}"
    hi = None
    for base, data in records:
        off = 0
        while off < len(data):
            addr = base + off
            a_hi = (addr >> 16) & 0xffff
            if a_hi != hi:
                out.append(rec(2, 0, 4, bytes([(a_hi >> 8) & 0xff, a_hi & 0xff]))); hi = a_hi
            n = min(16, len(data) - off, 0x10000 - (addr & 0xffff))
            out.append(rec(n, addr & 0xffff, 0, data[off:off+n])); off += n
    out.append(":00000001FF")
    return "\n".join(out) + "\n"

def blob(man, app, out):
    """Streamable signed image = manifest(96) || payload. This is exactly what
    the device writes to STAGING (via USB in Phase 2, or SWD to STAGING_BASE to
    test the installer now)."""
    data = open(man, "rb").read() + open(app, "rb").read()
    open(out, "wb").write(data)
    print("blob ->", out, f"({len(data)} bytes; write to 0x{0x08020000:08x})")

def merge(bl, man, app, out):
    recs = [(BL_BASE, open(bl, "rb").read()),
            (MANIFEST_ADDR, open(man, "rb").read()),
            (APP_BASE, open(app, "rb").read())]
    open(out, "w", newline="\n").write(ihex(recs))
    print("merged ->", out)

if __name__ == "__main__":
    a = sys.argv
    if len(a) < 2: print(__doc__); sys.exit(2)
    if   a[1] == "keygen": keygen()
    elif a[1] == "sign":   sign(a[2], a[3], a[4])
    elif a[1] == "verify": verify(a[2], a[3])
    elif a[1] == "blob":   blob(a[2], a[3], a[4])
    elif a[1] == "merge":  merge(a[2], a[3], a[4], a[5])
    else: print(__doc__); sys.exit(2)
